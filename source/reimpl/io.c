// Il gioco apre i suoi file con path relativi ("data.pak", "save/config_.xml",
// "../movie/") e non chiama mai chdir: su Vita un path relativo non risolve.
// I .pak stanno in DATA_PATH "assets/", quindi qui si ancora una volta sola,
// nel punto dove passano tutti i chiamanti, invece di toccare ogni call site.
static const char * soloader_path(const char * path, char * buf, size_t buflen) {
    if (!path || !path[0])
        return path;
    if (strchr(path, ':'))   // gia' un path Vita: ux0:, app0:, host0:
        return path;
    // I path unix di sistema li gestiscono i casi speciali dei singoli wrapper.
    // Tutto il resto che inizia con "/" (es. "/save") per il gioco e' relativo
    // alla propria root, non alla root del filesystem: va ancorato anche quello.
    if (path[0] == '/') {
        static const char * sysroots[] = { "/proc", "/sys", "/dev", "/system", "/data", "/sdcard", "/mnt" };
        for (unsigned i = 0; i < sizeof(sysroots) / sizeof(sysroots[0]); i++) {
            size_t n = strlen(sysroots[i]);
            if (strncmp(path, sysroots[i], n) == 0 && (path[n] == '/' || path[n] == '\0'))
                return path;
        }
        snprintf(buf, buflen, DATA_PATH "assets%s", path);
        return buf;
    }
    if (strncmp(path, "./", 2) == 0)
        path += 2;
    if (strncmp(path, "../", 3) == 0)  // un livello sopra assets/
        snprintf(buf, buflen, DATA_PATH "%s", path + 3);
    else
        snprintf(buf, buflen, DATA_PATH "assets/%s", path);
    return buf;
}

FILE * fopen_soloader(const char * filename, const char * mode) {
    if (strcmp(filename, "/proc/cpuinfo") == 0) {
        return fopen_soloader("app0:/cpuinfo", mode);
    } else if (strcmp(filename, "/proc/meminfo") == 0) {
        return fopen_soloader("app0:/meminfo", mode);
    }

    char pathbuf[512];
    filename = soloader_path(filename, pathbuf, sizeof(pathbuf));

#ifdef USE_SCELIBC_IO
    FILE* ret = sceLibcBridge_fopen(filename, mode);
#else
    FILE* ret = fopen(filename, mode);
#endif

    if (ret)
        l_debug("fopen(%s, %s): %p", filename, mode, ret);
    else
        l_warn("fopen(%s, %s): %p", filename, mode, ret);

    return ret;
}

int open_soloader(const char * path, int oflag, ...) {
    if (strcmp(path, "/proc/cpuinfo") == 0) {
        return open_soloader("app0:/cpuinfo", oflag);
    } else if (strcmp(path, "/proc/meminfo") == 0) {
        return open_soloader("app0:/meminfo", oflag);
    } else if (strcmp(path, "/dev/urandom") == 0) {
        return open_soloader("app0:/urandom", oflag);
    }

    mode_t mode = 0666;
    if (((oflag & BIONIC_O_CREAT) == BIONIC_O_CREAT) ||
        ((oflag & BIONIC_O_TMPFILE) == BIONIC_O_TMPFILE)) {
        va_list args;
        va_start(args, oflag);
        mode = (mode_t)(va_arg(args, int));
        va_end(args);
    }

    char pathbuf[512];
    path = soloader_path(path, pathbuf, sizeof(pathbuf));

    oflag = oflags_bionic_to_newlib(oflag);
    int ret = open(path, oflag, mode);
    if (ret >= 0)
        l_debug("open(%s, %x): %i", path, oflag, ret);
    else
        l_warn("open(%s, %x): %i", path, oflag, ret);
    return ret;
}

int fstat_soloader(int fd, stat64_bionic * buf) {
    struct stat st;
    int res = fstat(fd, &st);

    if (res == 0)
        stat_newlib_to_bionic(&st, buf);

    l_debug("fstat(%i): %i", fd, res);
    return res;
}

int stat_soloader(const char * path, stat64_bionic * buf) {
    if (strcmp(path, "/system/lib/libOpenSLES.so") == 0) {
        l_debug("stat(%s): returning 0 in case this is a check for OpenSLES support", path);
        return 0;
    }

    char pathbuf[512];
    path = soloader_path(path, pathbuf, sizeof(pathbuf));

    struct stat st;
    int res = stat(path, &st);

    if (res == 0)
        stat_newlib_to_bionic(&st, buf);

    l_debug("stat(%s): %i", path, res);
    return res;
}

